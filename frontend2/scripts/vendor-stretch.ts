// Writes src/audio/engine/stretch-wasm.generated.ts from the pinned npm package. After changing its version:
//   deno run --allow-read --allow-write scripts/vendor-stretch.ts
// The package only offers its own AudioWorkletProcessor, and the engine needs the stretcher inside its one worklet, on its
// sample clock. So this takes the WebAssembly out of it, and `stretcher.ts` drives that. Its export names are minified
// by the build, so a new version means checking them. `stretcher.test.ts` holds this file to the package.
import { STRETCH_VERSION, wasmOfPackage } from "./stretch-package.ts";

const source = Deno.readTextFileSync(new URL("../node_modules/signalsmith-stretch/SignalsmithStretch.mjs", import.meta.url));
const out = `// Generated by scripts/vendor-stretch.ts from signalsmith-stretch ${STRETCH_VERSION} (MIT). Don't edit.
export const STRETCH_WASM_BASE64 = "${wasmOfPackage(source)}";
`;
Deno.writeTextFileSync(new URL("../src/audio/engine/stretch-wasm.generated.ts", import.meta.url), out);
